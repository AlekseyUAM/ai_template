"""Сопоставление путей, записанных в разном стиле.

Один и тот же каталог приходит из разных источников: пользователь вводит путь
в форме, Claude Code пишет cwd в журнал, registry хранит путь из конфига.
Расхождение в стиле слэшей, хвостовой слэш или регистр буквы диска не должно
означать «другой проект». Нормализация нужна только для сравнения — наружу
пути отдаются в том виде, в каком их задал вызывающий.
"""

import re

_DRIVE_RE = re.compile(r"^[A-Za-z]:")


def normalize_path(path: str) -> str:
    """Привести путь к виду, пригодному для сопоставления.

    Слэши — к прямым, хвостовой слэш снимается, Windows-путь (с буквой диска)
    приводится к нижнему регистру: Windows не различает регистр. Пути POSIX
    регистр сохраняют — там это разные каталоги.
    """
    if not path:
        return path
    norm = path.replace("\\", "/")
    # Пустая строка ключом быть не может: "/" схлопывать нельзя.
    norm = norm.rstrip("/") or norm[:1]
    if _DRIVE_RE.match(norm):
        norm = norm.casefold()
    return norm


def same_path(a: str, b: str) -> bool:
    """Один ли это путь с точностью до стиля записи."""
    return normalize_path(a) == normalize_path(b)
