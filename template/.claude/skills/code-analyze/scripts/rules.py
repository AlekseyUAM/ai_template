# ── Queries in a loop ────────────────────────────────────────

# Query object methods that access the DBMS. We require a preceding ".", so
# the global Выполнить("code string") operator does not fall here.
_QUERY_EXEC_NAMES = {"ВЫПОЛНИТЬ", "ВЫПОЛНИТЬПАКЕТ", "EXECUTE", "EXECUTEBATCH"}
_NEW_KW = {"НОВЫЙ", "NEW"}
_QUERY_TYPE = {"ЗАПРОС", "QUERY"}
_METHOD_KW = {"ПРОЦЕДУРА", "PROCEDURE", "ФУНКЦИЯ", "FUNCTION"}


def _query_execute_lines(model):
    """Lines with a `<object>.Выполнить(` / `.ВыполнитьПакет(` call (Запрос method)."""
    lines = []
    toks = model.tokens
    for k in range(len(toks) - 2):
        t0, t1, t2 = toks[k], toks[k + 1], toks[k + 2]
        if (t0.kind == "op" and t0.value == "."
                and t1.kind == "ident" and t1.value.upper() in _QUERY_EXEC_NAMES
                and t2.kind == "op" and t2.value == "("):
            lines.append(t1.line)
    return lines


def _new_query_lines(model):
    """Lines with the `Новый Запрос` constructor."""
    lines = []
    toks = model.tokens
    for k in range(len(toks) - 1):
        t0, t1 = toks[k], toks[k + 1]
        if (t0.kind == "ident" and t0.value.upper() in _NEW_KW
                and t1.kind == "ident" and t1.value.upper() in _QUERY_TYPE):
            lines.append(t1.line)
    return lines


def _methods_covering_lines(model, lines):
    """Set of method NAMES (upper) whose body contains at least one of the lines."""
    names = set()
    if not lines:
        return names
    for m in model.methods:
        if not m.name:
            continue
        for ln in lines:
            if m.header_line <= ln <= m.end_line:
                names.add(m.name.upper())
                break
    return names


def _local_call_sites_in_loops(model, method_names):
    """Calls of local methods from method_names in loop bodies.

    A local call is `Имя(` without a preceding dot (qualified calls
    `Объект.Метод(` and `ОбщийМодуль.Метод(` resolve outside the module - not our case,
    depth 1 works only within the module). The method declaration header itself
    is excluded. Returns a list of (line, name-as-in-code)."""
    out = []
    if not method_names:
        return out
    toks = model.tokens
    n = len(toks)
    for k in range(n - 1):
        t = toks[k]
        if t.kind != "ident" or t.value.upper() not in method_names:
            continue
        nxt = toks[k + 1]
        if not (nxt.kind == "op" and nxt.value == "("):
            continue
        prev = toks[k - 1] if k > 0 else None
        if prev is not None and prev.kind == "op" and prev.value == ".":
            continue  # Объект.Метод( - not a local call
        if prev is not None and prev.kind == "ident" and prev.value.upper() in _METHOD_KW:
            continue  # method declaration header
        if model.is_in_loop(t.line):
            out.append((t.line, t.value))
    return out


@rule(code="query-execute-in-loop", severity="warning",
      title="Запрос.Выполнить() в цикле — вынесите запрос из цикла")
def check_query_execute_in_loop(ctx):
    """Flag query execution (`.Выполнить()`/`.ВыполнитьПакет()`) in a loop body.

    "One should strive to minimize the number of DBMS queries". A query on every
    loop iteration is a typical anti-pattern: as a rule, it can be moved out of the loop and
    executed once, selecting all needed data by list (condition В (&Список)).
    Acceptable exceptions (portion processing, virtual tables with a slice date) are
    checked manually (query-review); with a justified exception there must be a
    comment nearby.
    """
    out = []
    model = ctx.model
    for ln in _query_execute_lines(model):
        if model.is_in_loop(ln):
            out.append(Finding(
                code="query-execute-in-loop",
                severity="warning",
                line=ln,
                message=(
                    "Выполнение запроса (.Выполнить()) в цикле: запрос к СУБД на каждой "
                    "итерации. Вынесите запрос из цикла — выберите все данные одним запросом "
                    "(условие В (&Список)). Исключения (порционная обработка, ВТ с датой среза) "
                    "обоснуйте комментарием."
                ),
            ))
    return out


