# rules.py - registry of automatic checks for 1C BSL code.
#
# Rules work on the structural module model (bsl_model.Module) - tokens,
# methods, loops, Перем declarations. The model is built in pure Python, without
# external dependencies, so (unlike query-analyze) the rules are never
# "skipped" - the model is always available.
#
# We do NOT duplicate BSL Language Server (bsl_ls) diagnostics: here are only
# checks that bsl_ls does not have. Requirements that cannot be reliably
# scripted are moved to the manual checklist of the bsl-coding-standards skill.

import json
import re
from dataclasses import dataclass
from pathlib import Path

import bsl_model


@dataclass
class Finding:
    code: str
    severity: str  # error | warning | info
    line: int
    message: str


@dataclass
class Rule:
    code: str
    severity: str
    title: str
    fn: object


RULES = []


def rule(code, severity, title):
    def deco(fn):
        RULES.append(Rule(code=code, severity=severity, title=title, fn=fn))
        return fn
    return deco


# ── System enums and value sets ──────────────────────────────

# Data is generated by tools/update_system_names.py from the platform help
# (.hbk) and sits next to rules.py. Without the file the rules simply do not fire.
_SYSTEM_DATA_PATH = Path(__file__).with_name("system_enums.json")


def _system_names():
    """Return (members, samples, reserved) from system_enums.json.

    members: casefold(type name) -> set(casefold(value)) | None (do not check)
    samples: casefold(type name) -> [values for the message]
    reserved: casefold(type name) -> canonical type name
    """
    members, samples, reserved = {}, {}, {}
    try:
        data = json.loads(_SYSTEM_DATA_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return members, samples, reserved

    def add_type(name, name_en, ru_values, en_values, allowed):
        if name:
            key = name.casefold()
            members[key] = allowed
            samples[key] = ru_values[:12]
            reserved[key] = name
        if name_en:
            key = name_en.casefold()
            members[key] = allowed
            samples[key] = (en_values or ru_values)[:12]
            reserved[key] = name

    for name, info in (data.get("enums") or {}).items():
        values = info.get("values") or []
        ru_values = [pair[0] for pair in values if pair]
        en_values = [pair[1] for pair in values if len(pair) > 1 and pair[1]]
        allowed = {v.casefold() for v in ru_values + en_values} or None
        add_type(name, info.get("name_en"), ru_values, en_values, allowed)

    for name, info in (data.get("value_sets") or {}).items():
        values = info.get("values") or []
        ru_values = [pair[0] for pair in values if pair]
        en_values = [pair[1] for pair in values if len(pair) > 1 and pair[1]]
        allowed = None if info.get("open") else (
            {v.casefold() for v in ru_values + en_values} or None)
        add_type(name, info.get("name_en"), ru_values, en_values, allowed)

    return members, samples, reserved


SYSTEM_MEMBERS, SYSTEM_SAMPLES, SYSTEM_RESERVED = _system_names()


class ModuleContext:
    """Analysis context of a single module. Lazy wrapper over bsl_model.Module."""

    def __init__(self, text):
        self.text = text
        self._model = None
        self._lines = None
        self._code = None

    @property
    def model(self):
        if self._model is None:
            self._model = bsl_model.Module(self.text)
        return self._model

    @property
    def lines(self):
        if self._lines is None:
            self._lines = self.text.split("\n")
        return self._lines

    @property
    def code(self):
        """Text without string and comment content (length/lines preserved)."""
        if self._code is None:
            self._code = self.model.sanitized
        return self._code

    def code_line(self, lineno):
        """Sanitized line by number (1-based) or ''."""
        code_lines = self.code.split("\n")
        if 1 <= lineno <= len(code_lines):
            return code_lines[lineno - 1]
        return ""


def run_all(ctx):
    findings = []
    for r in RULES:
        findings.extend(r.fn(ctx))
    return findings


# ── Mass string concatenation ────────────────────────────────

# Accumulator assignment: "Имя = ... Имя ... " with the "+" operator.
_ASSIGN_RE = re.compile(
    r"^\s*([A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё0-9_]*)\s*=\s*(.+)$",
    re.UNICODE,
)


# Operators that indicate a boolean/comparison accumulator (not string concatenation):
# if they are present in the right-hand side of "+", it is arithmetic/logic, not strings.
_NON_STRING_OP_RE = re.compile(
    r"(<>|<=|>=|[<>])|(?<![A-Za-zА-Яа-яЁё0-9_])(И|ИЛИ|НЕ|And|Or|Not)(?![A-Za-zА-Яа-яЁё0-9_])",
    re.UNICODE | re.IGNORECASE,
)


# Numeric accumulator names: "Сумма = Сумма + ..." - arithmetic, not strings.
_NUMERIC_ACCUMULATOR_RE = re.compile(
    r"(?i)(сумм|стоимост|себестоим|количеств|итог|цен[аы]?|ндс|вес|объ[её]м|"
    r"ставк|процент|сальдо|остат|оборот|прибыл|убыт|рентабельн|начислен|"
    r"удержан|дней|часов|минут|секунд)"
)


@rule(code="string-concat-in-loop", severity="warning",
      title="Конкатенация строк в цикле — используйте СтрСоединить")
def check_string_concat_in_loop(ctx):
    """Flag string accumulation by concatenation inside a loop.

    "For mass string concatenation operations, use the platform methods
    СтрРазделить and СтрСоединить". The classic signal is an
    accumulator "Текст = Текст + ..." in the loop body: on large volumes it is
    quadratic in time and memory. The threshold (~1000 operations) is unknown to the script,
    so severity=warning, and the message explains the applicability condition.

    Works on the model: for each loop it scans the lines of its body; flags an
    assignment where the left-hand side repeats in the right-hand side and "+" is present.
    To avoid catching boolean/comparison accumulators (a frequent false positive,
    e.g. `Флаг = Флаг Или X + 1 > 0`), no finding is produced if the right-hand side has
    comparison operators (`<`,`>`,`<=`,`>=`,`<>`) or logical operators
    (И/ИЛИ/НЕ/And/Or/Not). Numeric accumulators by name (`Сумма`, `Стоимость`,
    `Количество`, `Себестоимость` etc., see _NUMERIC_ACCUMULATOR_RE) are not flagged:
    for such names "= ... + ..." is arithmetic, not string concatenation.
    """
    out = []
    seen = set()
    model = ctx.model
    for loop in model.loops:
        for ln in range(loop.header_end_line + 1, loop.end_line):
            if ln in seen:
                continue
            text_line = ctx.code_line(ln)
            m = _ASSIGN_RE.match(text_line)
            if not m:
                continue
            lhs, rhs = m.group(1), m.group(2)
            if "+" not in rhs:
                continue
            if not re.search(r"\b" + re.escape(lhs) + r"\b", rhs, re.UNICODE | re.IGNORECASE):
                continue
            # Logical/comparison accumulator - not strings, skip.
            if _NON_STRING_OP_RE.search(rhs):
                continue
            # Numeric accumulator by name (Сумма, Стоимость...) - skip.
            if _NUMERIC_ACCUMULATOR_RE.search(lhs):
                continue
            seen.add(ln)
            out.append(Finding(
                    code="string-concat-in-loop",
                    severity="warning",
                    line=ln,
                    message=(
                        f"Конкатенация-аккумулятор «{lhs}» в цикле: на массовых объёмах "
                        f"(≈1000+ операций) это медленно и расходует память. "
                        f"Накапливайте части в Массив и соберите через СтрСоединить."
                    ),
                ))
    return out


# ── Search in value collections ──────────────────────────────

# Column list: two or more identifiers separated by commas.
_COLUMN_LIST_RE = re.compile(
    r"^\s*[A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё0-9_]*\s*"
    r"(?:,\s*[A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё0-9_]*\s*)+$",
    re.UNICODE,
)
_FIND_NAMES = {"НАЙТИ", "FIND"}


@rule(code="tv-find-multiple-columns", severity="warning",
      title="ТаблицаЗначений.Найти по нескольким колонкам — индекс не используется")
def check_tv_find_multiple_columns(ctx):
    """Flag a ".Найти(Значение, "Кол1, Кол2")" call with multiple columns.

    "Do not use the Найти method to search by multiple columns ...
    the Найти method searches using an index on only one field".
    With multiple columns the search scans all rows.
    To search by multiple columns use НайтиСтроки with an index
    matching the search structure.

    Signal: a ".Найти(" call with a string literal among its arguments -
    a list of two or more comma-separated columns. severity=warning.
    """
    out = []
    tokens = ctx.model.tokens
    n = len(tokens)
    k = 0
    while k < n - 2:
        t = tokens[k]
        if (t.kind == "op" and t.value == "."
                and tokens[k + 1].kind == "ident"
                and tokens[k + 1].value.upper() in _FIND_NAMES
                and tokens[k + 2].kind == "op" and tokens[k + 2].value == "("):
            # Collect arguments up to the matching ')'.
            j = k + 3
            depth = 1
            col_literal = None
            while j < n and depth > 0:
                tj = tokens[j]
                if tj.kind == "op" and tj.value == "(":
                    depth += 1
                elif tj.kind == "op" and tj.value == ")":
                    depth -= 1
                elif depth == 1 and tj.kind == "string" and _COLUMN_LIST_RE.match(tj.value):
                    col_literal = tj.value.strip()
                j += 1
            if col_literal is not None:
                out.append(Finding(
                    code="tv-find-multiple-columns",
                    severity="warning",
                    line=tokens[k + 1].line,
                    message=(
                        f"Найти по нескольким колонкам («{col_literal}»): индекс применяется "
                        f"только по одному полю — поиск пойдёт перебором всех строк. "
                        f"Используйте НайтиСтроки с индексом, совпадающим со структурой поиска."
                    ),
                ))
            k = j
            continue
        k += 1
    return out


# ── Variable naming rules ────────────────────────────────────

def _iter_var_names(model):
    """yield (name, line, source) for declared Перем and method parameters."""
    for name, line, _is_export in model.var_declarations:
        yield name, line, "переменная"
    for m in model.methods:
        for p in m.params:
            yield p, m.header_line, "параметр"


@rule(code="var-name-starts-with-underscore", severity="warning",
      title="Имя переменной начинается с подчёркивания — запрещено")
def check_var_name_starts_with_underscore(ctx):
    """Flag variables and parameters whose name starts with "_".

    "Variable names must not start with an underscore".
    Перем declarations and method parameters are checked - there the name is
    definitely a variable name (unlike arbitrary dot accesses).
    """
    out = []
    for name, line, kind in _iter_var_names(ctx.model):
        if name.startswith("_"):
            out.append(Finding(
                code="var-name-starts-with-underscore",
                severity="warning",
                line=line,
                message=f"Имя ({kind}) «{name}» начинается с подчёркивания — запрещено стандартом.",
            ))
    return out


@rule(code="var-name-single-char", severity="info",
      title="Имя переменной из одного символа — допустимо только для счётчиков циклов")
def check_var_name_single_char(ctx):
    """Flag single-character names of declared Перем and parameters.

    "Variable names must not consist of a single character. Single-character
    names are allowed only for loop counters".
    Loop counters (Для Сч = ...) are declared in the loop header, not via Перем,
    and are not parameters, so they do not fall under the rule. severity=info -
    this is a style recommendation.
    """
    out = []
    for name, line, kind in _iter_var_names(ctx.model):
        if len(name) == 1:
            out.append(Finding(
                code="var-name-single-char",
                severity="info",
                line=line,
                message=(
                    f"Имя ({kind}) «{name}» состоит из одного символа — "
                    f"односимвольные имена допустимы только для счётчиков циклов."
                ),
            ))
    return out


# ── Raising exceptions in code ───────────────────────────────

_RAISE_NAMES = {"ВЫЗВАТЬИСКЛЮЧЕНИЕ", "RAISE"}
_CANCEL_PARAM = {"ОТКАЗ", "CANCEL"}


@rule(code="raise-in-cancel-event", severity="info",
      title="ВызватьИсключение в обработчике с параметром Отказ — рассмотрите установку Отказ")
def check_raise_in_cancel_event(ctx):
    """Flag ВызватьИсключение in a method that has an "Отказ" parameter.

    "It is unacceptable in the events ОбработкаПроверкиЗаполнения, ОбработкаПроведения,
    ПередЗаписью, ПриЗаписи, ПередУдалением etc. to raise exceptions to show
    stopping warnings that the user must handle.
    Instead, set the Отказ parameter to Истина and
    output messages to the user" - that way the user sees all reasons at once.

    The "Отказ" parameter is a reliable sign of such a handler (it is the standard
    stop mechanism). severity=info: the standard allows an exception when
    the situation is truly exceptional - this is a review hint, not a verdict.
    """
    model = ctx.model
    cancel_methods = [
        m for m in model.methods
        if any(p.upper() in _CANCEL_PARAM for p in m.params)
    ]
    if not cancel_methods:
        return []
    out = []
    for t in model.tokens:
        if t.kind == "ident" and t.value.upper() in _RAISE_NAMES:
            for m in cancel_methods:
                if m.header_line <= t.line <= m.end_line:
                    out.append(Finding(
                        code="raise-in-cancel-event",
                        severity="info",
                        line=t.line,
                        message=(
                            f"ВызватьИсключение в обработчике «{m.name}» с параметром Отказ: "
                            f"для останавливающих предупреждений пользователю устанавливайте "
                            f"Отказ = Истина и выводите сообщения (если ситуация не исключительная)."
                        ),
                    ))
                    break
    return out


# ── Catching exceptions in code ──────────────────────────────

@rule(code="error-description-without-stack", severity="info",
      title="ОписаниеОшибки() не возвращает стек — используйте ПодробноеПредставлениеОшибки")
def check_error_description_without_stack(ctx):
    """Flag a call to the global function ОписаниеОшибки().

    "Do not use the ОписаниеОшибки function instead of
    ОбработкаОшибок.ПодробноеПредставлениеОшибки, because it is uninformative for
    the developer since it does not return the stack in the error text".

    Detected by the ОписаниеОшибки identifier followed by "(", which
    is not a dot access (that is, it is exactly the global function).
    """
    out = []
    toks = ctx.model.tokens
    n = len(toks)
    for i, t in enumerate(toks):
        if t.kind != "ident" or t.value.upper() != "ОПИСАНИЕОШИБКИ":
            continue
        if not (i + 1 < n and toks[i + 1].kind == "op" and toks[i + 1].value == "("):
            continue
        if i > 0 and toks[i - 1].kind == "op" and toks[i - 1].value == ".":
            continue  # dot access - not the global function
        out.append(Finding(
            code="error-description-without-stack",
            severity="info",
            line=t.line,
            message=(
                "ОписаниеОшибки() не возвращает стек вызовов и неинформативна для "
                "разработчика — используйте ОбработкаОшибок.ПодробноеПредставлениеОшибки()."
            ),
        ))
    return out


# ── Determining the type of a variable value ─────────────────

def _followed_by_string_compare(toks, j, n):
    """True if a comparison (= or <>) with a string literal follows index j."""
    if j >= n:
        return False
    if toks[j].kind == "op" and toks[j].value == "=":
        k = j + 1
    elif (j + 1 < n and toks[j].kind == "op" and toks[j].value == "<"
          and toks[j + 1].kind == "op" and toks[j + 1].value == ">"):
        k = j + 2
    else:
        return False
    for m in range(k, min(k + 3, n)):
        if toks[m].kind == "string":
            return True
    return False


@rule(code="type-check-via-metadata-name", severity="warning",
      title="Тип определяется сравнением Метаданные().Имя со строкой — используйте ТипЗнч() = Тип()")
def check_type_check_via_metadata_name(ctx):
    """Flag type determination via the comparison "...Метаданные().Имя = "Имя"".

    "The type of a variable value must be determined by comparing it
    with the type, not by any other method". CORRECT:
    ТипЗнч(Ссылка) = Тип("ДокументСсылка...."); INCORRECT:
    Ссылка.Метаданные().Имя = "...".

    Detected by the token sequence ".Метаданные ( ) . Имя" followed
    by a comparison (=/<>) with a string literal. Accesses to Метаданные().Имя
    without a comparison with a string (e.g. for logging) are not flagged.
    """
    out = []
    toks = ctx.model.tokens
    n = len(toks)
    i = 0
    while i < n - 5:
        if (toks[i].kind == "op" and toks[i].value == "."
                and toks[i + 1].kind == "ident" and toks[i + 1].value.upper() == "МЕТАДАННЫЕ"
                and toks[i + 2].kind == "op" and toks[i + 2].value == "("
                and toks[i + 3].kind == "op" and toks[i + 3].value == ")"
                and toks[i + 4].kind == "op" and toks[i + 4].value == "."
                and toks[i + 5].kind == "ident" and toks[i + 5].value.upper() == "ИМЯ"):
            if _followed_by_string_compare(toks, i + 6, n):
                out.append(Finding(
                    code="type-check-via-metadata-name",
                    severity="warning",
                    line=toks[i + 1].line,
                    message=(
                        "Тип определяется сравнением Метаданные().Имя со строкой — "
                        "используйте ТипЗнч(Значение) = Тип(\"…\"): имя метаданного ненадёжно "
                        "(регистр/переименование) и работает медленнее."
                    ),
                ))
            i += 6
            continue
        i += 1
    return out


# ── Copying rows between value tables ────────────────────────

_COLUMNS_IN_HEADER = re.compile(r"\.\s*Колонки\b", re.IGNORECASE | re.UNICODE)


@rule(code="column-copy-loop", severity="info",
      title="Копирование строк ТЗ перебором колонок — используйте ЗаполнитьЗначенияСвойств")
def check_column_copy_loop(ctx):
    """Flag copying row values of a value table (ТЗ) in a `.Колонки` loop.

    "When copying rows between different value tables ... with a similar
    column composition, use the global context method
    ЗаполнитьЗначенияСвойств" - it is much more efficient than iterating columns.

    Signal: a `Для Каждого <Колонка> Из <...>.Колонки Цикл` loop whose body has
    an assignment by column name `<...>[<Колонка>.Имя] = ...`. severity=info.
    """
    out = []
    model = ctx.model
    code_lines = ctx.code.split("\n")
    for loop in model.loops:
        lv = loop.loop_var
        if not lv:
            continue
        header_src = " ".join(code_lines[loop.header_line - 1:loop.header_end_line])
        if not _COLUMNS_IN_HEADER.search(header_src):
            continue
        assign_re = re.compile(
            r"\[\s*" + re.escape(lv) + r"\s*\.\s*Имя\s*\]\s*=",
            re.IGNORECASE | re.UNICODE,
        )
        for ln in range(loop.header_end_line + 1, loop.end_line):
            if assign_re.search(ctx.code_line(ln)):
                out.append(Finding(
                    code="column-copy-loop",
                    severity="info",
                    line=loop.header_line,
                    message=(
                        "Копирование значений по колонкам в цикле по «.Колонки» — "
                        "используйте ЗаполнитьЗначенияСвойств(СтрокаПриёмника, СтрокаИсточника): "
                        "короче и значительно быстрее."
                    ),
                ))
                break
    return out


# ── General requirements for constructing statements ─────────

# Control character codes that have an equivalent in the system Символы set.
_SYMBOL_CODES = {
    "9": "Таб", "10": "ПС", "11": "ВТаб", "12": "ПФ", "13": "ВК", "160": "НПП",
}


@rule(code="char-code-literal", severity="info",
      title="Символ(код) вместо системного набора Символы.*")
def check_char_code_literal(ctx):
    """Flag Символ(<code>) for standard separators - there is the Символы set.

    "System value sets must be used wherever they can be
    applied, for example instead of Символ(10) use Символы.ПС".

    Flags Символ(N) with the numeric literal N that has an equivalent in
    the Символы set (9→Таб, 10→ПС, 11→ВТаб, 12→ПФ, 13→ВК, 160→НПП). Символ(<var>)
    and other codes are not touched.
    """
    out = []
    toks = ctx.model.tokens
    n = len(toks)
    for i, t in enumerate(toks):
        if t.kind != "ident" or t.value.upper() != "СИМВОЛ":
            continue
        if i > 0 and toks[i - 1].kind == "op" and toks[i - 1].value == ".":
            continue
        if not (i + 3 < n and toks[i + 1].kind == "op" and toks[i + 1].value == "("
                and toks[i + 2].kind == "number"
                and toks[i + 3].kind == "op" and toks[i + 3].value == ")"):
            continue
        code = toks[i + 2].value
        name = _SYMBOL_CODES.get(code)
        if name:
            out.append(Finding(
                code="char-code-literal",
                severity="info",
                line=t.line,
                message=(
                    f"Символ({code}) — используйте системный набор: Символы.{name}."
                ),
            ))
    return out


# ── Form event handlers attached from code ───────────────────

_ATTACH_PREFIXES = ("ПОДКЛЮЧАЕМЫЙ_", "ATTACHABLE_")


@rule(code="attachable-handler-prefix", severity="info",
      title="Обработчик из УстановитьДействие без префикса Подключаемый_")
def check_attachable_handler_prefix(ctx):
    """Flag УстановитьДействие(<Событие>, "<Обработчик>") where the handler name
    does not start with the "Подключаемый_" prefix.

    "Form module event handlers that are set from code using the
    УстановитьДействие method are recommended to have the Подключаемый_ prefix"
    (Attachable_) - to distinguish them in unused method search results.

    The second string argument of the `.УстановитьДействие(...)` call is checked.
    An empty string (disabling the action) is skipped.
    """
    out = []
    toks = ctx.model.tokens
    n = len(toks)
    k = 0
    while k < n - 2:
        if (toks[k].kind == "op" and toks[k].value == "."
                and toks[k + 1].kind == "ident" and toks[k + 1].value.upper() == "УСТАНОВИТЬДЕЙСТВИЕ"
                and toks[k + 2].kind == "op" and toks[k + 2].value == "("):
            # Collect string arguments by index (depth 1).
            j = k + 3
            depth = 1
            arg_index = 0
            arg_string = {}      # argument index -> string literal (if the argument is a single string)
            arg_simple = {}      # argument index -> only one token
            while j < n and depth > 0:
                tj = toks[j]
                if tj.kind == "op" and tj.value == "(":
                    depth += 1
                elif tj.kind == "op" and tj.value == ")":
                    depth -= 1
                    if depth == 0:
                        break
                elif depth == 1 and tj.kind == "op" and tj.value == ",":
                    arg_index += 1
                elif depth == 1:
                    arg_simple[arg_index] = arg_simple.get(arg_index, 0) + 1
                    if tj.kind == "string":
                        arg_string[arg_index] = tj.value
                j += 1
            handler = arg_string.get(1)
            if handler and arg_simple.get(1) == 1:
                if not handler.upper().startswith(_ATTACH_PREFIXES):
                    out.append(Finding(
                        code="attachable-handler-prefix",
                        severity="info",
                        line=toks[k + 1].line,
                        message=(
                            f"Обработчик «{handler}» из УстановитьДействие — задайте имени префикс "
                            f"«Подключаемый_», чтобы отличать подключаемые обработчики."
                        ),
                    ))
            k = j
            continue
        k += 1
    return out


